def _xbm_data(rows: tuple[str, ...]) -> str:
    """Encode a readable row pattern as Tk-compatible XBM data."""
    if not rows or any(len(row) != len(rows[0]) for row in rows):
        raise ValueError("Icon rows must form a non-empty rectangle")
    width = len(rows[0])
    values: list[int] = []
    for row in rows:
        if set(row) - {"0", "1"}:
            raise ValueError("Icon rows may contain only 0 and 1")
        for offset in range(0, width, 8):
            byte = 0
            for bit, value in enumerate(row[offset : offset + 8]):
                if value == "1":
                    byte |= 1 << bit
            values.append(byte)
    encoded = ", ".join(f"0x{value:02x}" for value in values)
    return (
        f"#define icon_width {width}\n"
        f"#define icon_height {len(rows)}\n"
        f"static unsigned char icon_bits[] = {{\n  {encoded}\n}};\n"
    )


def create_icon(master: tk.Misc, name: str, color: str) -> tk.BitmapImage:
    """Create a transparent, theme-colored Tk bitmap icon."""
    try:
        rows = _ICON_ROWS[name]
    except KeyError as error:
        raise ValueError(f"Unknown icon: {name}") from error
    return tk.BitmapImage(master=master, data=_xbm_data(rows), foreground=color)


def create_app_icon(master: tk.Misc) -> tk.PhotoImage:
    """Create the purple application mark used by the native window title bar."""
    image = tk.PhotoImage(master=master, width=32, height=32)
    image.put("#5B4CF0", to=(0, 0, 32, 32))
    for rectangle in (
        (5, 7, 7, 25),
        (7, 6, 14, 8),
        (13, 7, 15, 25),
        (18, 7, 20, 25),
        (20, 6, 27, 8),
        (26, 7, 28, 25),
        (7, 23, 14, 25),
        (20, 23, 27, 25),
        (15, 14, 18, 17),
    ):
        image.put("#FFFFFF", to=rectangle)
    return image


def icon_names() -> tuple[str, ...]:
    """Return stable names for tests and UI composition."""
    return tuple(_ICON_ROWS)

